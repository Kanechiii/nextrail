test('toast queue caps visible messages, replaces duplicates, and does not persist',()=>{
  let current=[]
  for(let i=1;i<=4;i++)current=appendFeedback(current,'success','Action '+i,i)
  assert.deepEqual(current.map(item=>item.message),['Action 2','Action 3','Action 4'])
  current=appendFeedback(current,'error','Action 3',5)
  assert.deepEqual(current.map(item=>item.message),['Action 2','Action 4','Action 3'])
  assert.equal(current[2].id,5)
  assert.equal(current[2].kind,'error')
  assert.deepEqual(removeFeedback(current,4).map(item=>item.id),[2,5])
  assert.equal(appendFeedback(current,'info','   ',6),current)
  assert.doesNotMatch(toast,/localStorage|sessionStorage|navigator\.sendBeacon/)
})

